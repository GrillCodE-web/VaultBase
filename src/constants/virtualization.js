/**
 * Параметры виртуализации списков (CLEAN-010): overscan и высоты строк
 * собраны в одном месте, чтобы тюнинг скролла не требовал правок в 6 файлах.
 *
 * overscan — сколько строк рендерится за пределами вьюпорта (сверху и снизу).
 * Больше → меньше белых полос при быстрой прокрутке, но больше лишних
 * рендеров. Значения подобраны под высоту строки и сложность её контента.
 */

/** Карты (CardTable): лёгкая строка 38px, порог виртуализации низкий — хватает 10. */
export const CARDS_OVERSCAN = 10

/** Заказы (OrdersTable): строка с раскрытием до 180px — 20 против белых полос. */
export const ORDERS_OVERSCAN = 20

/** Профили (ProfilesTable): строка с раскрытием до 450px — 20. */
export const PROFILES_OVERSCAN = 20

/** Imap-список писем: строка 65px, контент простой — 5. */
export const IMAP_OVERSCAN = 5

/** Прокси: строка 50px — 5. */
export const PROXIES_OVERSCAN = 5

/** Магазины: строка 60px — 5. */
export const SHOPS_OVERSCAN = 5
